-- Shared inventory catalog. Stock stays in bago_east_* and bago_west_*.
-- A photo row is a reference, not a stock count.

CREATE TABLE IF NOT EXISTS inventory_categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    entry_mode VARCHAR(20) NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT ck_inventory_category_entry_mode CHECK (
        entry_mode IN ('scan_or_manual', 'manual_only')
    )
);

CREATE TABLE IF NOT EXISTS inventory_item_types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES inventory_categories (id),
    code VARCHAR(40) NOT NULL,
    name VARCHAR(80) NOT NULL,
    unit VARCHAR(20) NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT uq_inventory_item_type UNIQUE (category_id, code)
);

CREATE INDEX IF NOT EXISTS ix_inventory_item_types_category_id
    ON inventory_item_types (category_id);

CREATE TABLE IF NOT EXISTS inventory_images (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relative_path VARCHAR(500) NOT NULL,
    category_code VARCHAR(40),
    item_code VARCHAR(40),
    content_sha256 VARCHAR(64) NOT NULL UNIQUE,
    confirmed_quantity NUMERIC(14, 2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_inventory_image_class_pair CHECK (
        (category_code IS NULL AND item_code IS NULL)
        OR (category_code IS NOT NULL AND item_code IS NOT NULL)
    ),
    CONSTRAINT ck_inventory_image_quantity CHECK (confirmed_quantity >= 0)
);

